/**
 * Builds the admin's local-auth env file (`admin/.env.screenshots.local`) from
 * `supabase status -o json` of the LOCAL stack, so agents can sign in to the
 * admin and screenshot gated pages without touching the hosted project.
 *
 * Every slot points at the local stack: the DB target (local and the "prod"
 * slot, which a production build always uses), and auth. Pure so the loopback
 * guard is unit-testable; scripts/admin-screenshot-env.ts does the I/O.
 */
import { isLocalUrl } from './seed-guard';

/** Dev admin created by supabase/seed.sql (local stack only). */
export const DEV_ADMIN_ID = '00000000-0000-4000-a000-00000000ad01';
export const DEV_ADMIN_EMAIL = 'admin@ossus.test';

export type ScreenshotEnv = {
	SUPABASE_LOCAL_URL: string;
	SUPABASE_LOCAL_SERVICE_ROLE_KEY: string;
	SUPABASE_PROD_URL: string;
	SUPABASE_PROD_SERVICE_ROLE_KEY: string;
	NEXT_PUBLIC_SUPABASE_URL: string;
	NEXT_PUBLIC_SUPABASE_ANON_KEY: string;
	ADMIN_USER_IDS: string;
};

// JWTs and sb_* keys only: no whitespace, quotes or `=` that could break the file.
const KEY_SHAPE = /^[A-Za-z0-9._-]+$/;

/** The string fields of `supabase status -o json`. Throws on anything but an object. */
export function parseStatusJson(text: string): Record<string, string> {
	const data: unknown = JSON.parse(text);
	if (typeof data !== 'object' || data === null || Array.isArray(data)) {
		throw new Error('supabase status did not return a JSON object');
	}
	const out: Record<string, string> = {};
	for (const [k, v] of Object.entries(data)) if (typeof v === 'string') out[k] = v;
	return out;
}

function pickKey(status: Record<string, string>, names: string[], label: string): string {
	const value = names.map((n) => status[n]).find((v) => v !== undefined && v !== '');
	if (!value) throw new Error(`supabase status has no ${label} key (${names.join(' / ')})`);
	if (!KEY_SHAPE.test(value)) throw new Error(`supabase status ${label} key is malformed`);
	return value;
}

/** Throws unless API_URL is loopback and both keys are present and well-formed. */
export function buildScreenshotEnv(status: Record<string, string>): ScreenshotEnv {
	const url = status.API_URL;
	if (!url) throw new Error('supabase status has no API_URL — is the local stack running?');
	if (!isLocalUrl(url)) {
		throw new Error(`Refusing to write a non-local Supabase URL (${url}); local stack only.`);
	}
	const secret = pickKey(status, ['SECRET_KEY', 'SERVICE_ROLE_KEY'], 'secret');
	const publishable = pickKey(status, ['PUBLISHABLE_KEY', 'ANON_KEY'], 'publishable');
	return {
		SUPABASE_LOCAL_URL: url,
		SUPABASE_LOCAL_SERVICE_ROLE_KEY: secret,
		SUPABASE_PROD_URL: url,
		SUPABASE_PROD_SERVICE_ROLE_KEY: secret,
		NEXT_PUBLIC_SUPABASE_URL: url,
		NEXT_PUBLIC_SUPABASE_ANON_KEY: publishable,
		ADMIN_USER_IDS: DEV_ADMIN_ID,
	};
}

export function renderEnvFile(vars: ScreenshotEnv): string {
	const header = [
		'# Generated by `npm run admin:screenshot-env` from the local Supabase stack.',
		'# Local only: DB, the "prod" slot and auth all point at the local API. Do not commit.',
	];
	const body = Object.entries(vars).map(([k, v]) => `${k}=${v}`);
	return `${[...header, ...body].join('\n')}\n`;
}
